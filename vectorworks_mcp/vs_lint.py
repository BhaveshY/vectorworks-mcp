"""Static lint for Python scripts that call the Vectorworks ``vs`` module.

Wrong-typed ``vs.*`` arguments do not always raise a Python error inside
Vectorworks: e.g. ``vs.SetClFillFore(name, vs.RGBToColorIndex(r, g, b))``
(an int where the stub declares COLOR = ``(r, g, b)``) crashed Vectorworks 2024
with an access violation. ``vw_script`` therefore checks every ``vs.<name>``
reference against the SDK stub signatures in ``data/vs_signatures.json``
(generated by ``scripts/gen-vs-signatures.py``) before anything is sent.

Rejected (each issue carries the correct signature):
  * unknown ``vs.`` names;
  * wrong positional argument counts (POINT/POINT3D/VECTOR may be passed as one
    tuple or as separate coordinates; COLOR must be one ``(r, g, b)`` value);
  * a literal number, or a ``vs.*`` call returning a scalar (e.g.
    ``vs.RGBToColorIndex``), passed to a COLOR parameter;
  * a literal tuple/list passed to a scalar parameter (HANDLE, STRING, INTEGER,
    REAL, BOOLEAN ...); a literal string passed to a HANDLE parameter;
  * tuple-unpacking a ``vs.*`` result into the wrong number of names;
  * functions that open modal dialogs or wait for a click (they block the
    Vectorworks main thread).

The JSON is loaded lazily on the first call (never at server start-up).
Stdlib only.
"""

from __future__ import annotations

import ast
import json
from pathlib import Path
from typing import Any, Optional

_DATA = Path(__file__).resolve().parent / "data" / "vs_signatures.json"
_TABLE: Optional[dict] = None
_NAMES: Optional[frozenset] = None
_LOWER: Optional[dict] = None

_WIDTH = {"COLOR": 3, "POINT": 2, "POINT3D": 3, "VECTOR": 3}
_TUPLE_OK = {"COLOR", "POINT", "POINT3D", "VECTOR", "ARRAY", "ANY", "CRITERIA", "PROCEDURE", "TEXTSTYLE"}
_SCALAR = {"HANDLE", "STRING", "INTEGER", "LONGINT", "REAL", "BOOLEAN", "CHAR"}
_SCALAR_RETURNS = {"INTEGER", "LONGINT", "REAL", "BOOLEAN", "HANDLE", "color", "STRING", "DYNARRAY of CHAR"}
MAX_ISSUES = 20


def _load() -> dict:
    global _TABLE, _NAMES, _LOWER
    if _TABLE is None:
        data = json.loads(_DATA.read_text(encoding="utf-8"))
        _TABLE = data["f"]
        _NAMES = frozenset(data.get("names", []))
        _LOWER = {name.lower(): name for name in _TABLE}
    return _TABLE


def signature(name: str) -> str:
    """Human-readable signature, e.g. ``vs.SetClFillFore(clasName: STRING, color: COLOR)``."""
    entry = _load().get(name)
    if not entry:
        return ""
    params = ", ".join(f"{p}: {t}" for p, t in entry["p"])
    if entry.get("v"):
        params += ", ..."
    text = f"vs.{name}({params})"
    if entry.get("r"):
        text += f" -> {entry['r']}"
    return text


def _is_number(node: ast.AST) -> bool:
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
        node = node.operand
    return isinstance(node, ast.Constant) and isinstance(node.value, (int, float)) and not isinstance(node.value, bool)


def _is_seq(node: ast.AST) -> bool:
    return isinstance(node, (ast.Tuple, ast.List))


class _Linter(ast.NodeVisitor):
    def __init__(self) -> None:
        self.table = _load()
        self.aliases = {"vs"}
        self.direct: dict[str, str] = {}  # from vs import X as Y -> {Y: X}
        self.issues: list[dict[str, Any]] = []
        self.probed: set[str] = set()  # names guarded by hasattr(vs, "Name")
        self._checked_calls: set[int] = set()

    # -- helpers -------------------------------------------------------------
    def _issue(self, node: ast.AST, name: str, problem: str, severity: str = "warning") -> None:
        # "error" blocks the script (unknown function, wrong argument count,
        # dialog-opening call). Type mismatches are only warnings: live tests
        # (2026-10-11) showed Vectorworks accepts e.g. x, y for POINT and an
        # index for COLOR, so rejecting them would cost capability.
        if len(self.issues) >= MAX_ISSUES:
            return
        item: dict[str, Any] = {"line": getattr(node, "lineno", 0), "function": f"vs.{name}" if name else "",
                                "problem": problem, "severity": severity}
        sig = signature(name) if name else ""
        if sig:
            item["signature"] = sig
        self.issues.append(item)

    def _vs_name(self, func: ast.AST) -> Optional[str]:
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name) and func.value.id in self.aliases:
            return func.attr
        if isinstance(func, ast.Name) and func.id in self.direct:
            return self.direct[func.id]
        return None

    def _known(self, node: ast.AST, name: str) -> bool:
        if name in self.table or name in (_NAMES or ()) or name.startswith("__") or name in self.probed:
            return True
        hint = ""
        lowered = (_LOWER or {}).get(name.lower())
        if lowered:
            hint = f"; did you mean vs.{lowered}? (names are case-sensitive)"
        else:
            import difflib  # only on the failure path
            close = difflib.get_close_matches(name, list(self.table), n=3, cutoff=0.75)
            if close:
                hint = "; did you mean " + " / ".join("vs." + c for c in close) + "?"
        self._issue(node, "", f"unknown function vs.{name} (not in the Vectorworks 2024/2025 vs.py stub){hint}", severity="error")
        if lowered:
            self.issues[-1]["signature"] = signature(lowered)
        return False

    def _scalar_vs_call(self, node: ast.AST) -> Optional[str]:
        if isinstance(node, ast.Call):
            inner = self._vs_name(node.func)
            entry = self.table.get(inner or "")
            if entry and entry.get("r") in _SCALAR_RETURNS:
                return inner
        return None

    # -- visitors ------------------------------------------------------------
    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            if alias.name == "vs":
                self.aliases.add(alias.asname or "vs")

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module == "vs":
            for alias in node.names:
                if alias.name == "*":
                    continue
                if self._known(node, alias.name):
                    self.direct[alias.asname or alias.name] = alias.name

    def visit_Attribute(self, node: ast.Attribute) -> None:
        if isinstance(node.value, ast.Name) and node.value.id in self.aliases and id(node) not in self._checked_calls:
            self._known(node, node.attr)
        self.generic_visit(node)

    def visit_Assign(self, node: ast.Assign) -> None:
        if isinstance(node.value, ast.Call):
            name = self._vs_name(node.value.func)
            entry = self.table.get(name or "")
            ret = (entry or {}).get("r", "")
            if entry and ret.startswith("(") and ret.endswith(")"):
                want = len([part for part in ret[1:-1].split(",") if part.strip()])
                for target in node.targets:
                    if isinstance(target, (ast.Tuple, ast.List)) and not any(
                            isinstance(elt, ast.Starred) for elt in target.elts):
                        if len(target.elts) != want:
                            self._issue(node, name, f"vs.{name} returns {ret} ({want} values) but the result is "
                                                    f"unpacked into {len(target.elts)} names")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        name = self._vs_name(node.func)
        if name is not None:
            if isinstance(node.func, ast.Attribute):
                self._checked_calls.add(id(node.func))
            if self._known(node, name):
                entry = self.table.get(name)
                if entry:
                    self._check_call(node, name, entry)
        self.generic_visit(node)

    # -- the call check --------------------------------------------------------
    def _check_call(self, node: ast.Call, name: str, entry: dict) -> None:
        if entry.get("ui"):
            self._issue(node, name, f"vs.{name} opens a modal dialog or waits for a mouse click; that blocks the "
                                    "Vectorworks main thread (and the bridge) until the user reacts. Pass the values "
                                    "in the script instead", severity="error")
            return
        params = entry["p"]
        args = node.args
        if entry.get("v"):
            return
        if node.keywords or any(isinstance(arg, ast.Starred) for arg in args):
            return
        if len(args) == len(params):
            for arg, (pname, ptype) in zip(args, params):
                self._check_arg_type(node, name, arg, pname, ptype)
            return
        if len(args) < len(params):
            self._issue(node, name, f"too few arguments: {len(args)} given, {len(params)} expected", severity="error")
            return
        # More args than declared params: POINT/POINT3D/VECTOR may be passed as
        # separate coordinates (COLOR may not: it must be one (r, g, b) value).
        total = sum(1 if t == "COLOR" else _WIDTH.get(t, 1) for _, t in params)
        has_color = any(t == "COLOR" for _, t in params)
        if len(args) > total:
            self._issue(node, name, f"too many arguments: {len(args)} given, {len(params)} expected"
                                    + (f" (up to {total} with expanded coordinates)" if total != len(params) else "")
                                    + ("; COLOR must be one (r, g, b) tuple" if has_color else ""), severity="error")
            return
        index = sub = 0
        for arg in args:
            pname, ptype = params[index]
            width = 1 if ptype == "COLOR" else _WIDTH.get(ptype, 1)
            if sub == 0:
                if width == 1:
                    self._check_arg_type(node, name, arg, pname, ptype)
                    index += 1
                elif _is_seq(arg):
                    self._check_arg_type(node, name, arg, pname, ptype)
                    index += 1
                elif _is_number(arg):
                    sub = 1
                else:
                    return  # a variable at a POINT position: tuple or coordinate - cannot tell statically
            else:
                if not _is_number(arg) and not isinstance(arg, (ast.Name, ast.Attribute, ast.BinOp, ast.Subscript,
                                                                ast.Call, ast.UnaryOp)):
                    self._issue(node, name, f"argument {pname} ({ptype}) mixes expanded coordinates and a tuple")
                    return
                sub += 1
            if sub and sub == width:
                index += 1
                sub = 0
        if index < len(params) or sub:
            self._issue(node, name, f"argument count does not match: {len(args)} given for {len(params)} "
                                    "parameters (POINT = (x, y) or x, y; COLOR = (r, g, b))", severity="error")

    def _check_arg_type(self, node: ast.Call, name: str, arg: ast.AST, pname: str, ptype: str) -> None:
        if ptype == "COLOR":
            if _is_number(arg):
                self._issue(node, name, f"parameter {pname} is COLOR = (r, g, b) with 0..65535 components; got a "
                                        "number (a palette index crashes Vectorworks)")
            elif self._scalar_vs_call(arg):
                inner = self._scalar_vs_call(arg)
                self._issue(node, name, f"parameter {pname} is COLOR = (r, g, b) with 0..65535 components; got "
                                        f"vs.{inner}(...) which returns {self.table[inner]['r']}")
            elif _is_seq(arg) and len(arg.elts) != 3:
                self._issue(node, name, f"parameter {pname} is COLOR = (r, g, b); got a {len(arg.elts)}-tuple")
            return
        if ptype in ("POINT", "POINT3D", "VECTOR") and _is_number(arg):
            self._issue(node, name, f"parameter {pname} is {ptype} (a coordinate tuple); got a single number")
            return
        if ptype in ("POINT", "POINT3D", "VECTOR") and _is_seq(arg) and len(arg.elts) < 2:
            self._issue(node, name, f"parameter {pname} is {ptype}; got a {len(arg.elts)}-tuple")
            return
        if ptype in _SCALAR and _is_seq(arg):
            self._issue(node, name, f"parameter {pname} is {ptype}; got a literal tuple/list")
            return
        if ptype == "HANDLE" and isinstance(arg, ast.Constant) and isinstance(arg.value, str):
            self._issue(node, name, f"parameter {pname} is HANDLE; got a string literal (look the object up first, "
                                    "e.g. vs.GetObject(name))")


def _probed_names(tree: ast.AST) -> set[str]:
    """Names the script feature-tests with hasattr(vs, "Name") / getattr(vs, "Name", ...)."""
    names = set()
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in ("hasattr", "getattr")
                and len(node.args) >= 2 and isinstance(node.args[1], ast.Constant) and isinstance(node.args[1].value, str)):
            names.add(node.args[1].value)
    return names


def lint(code: str) -> list[dict[str, Any]]:
    """Return a list of issues (empty = clean). Never raises for bad input."""
    try:
        tree = ast.parse(code, "<vw_script>", "exec")
    except SyntaxError as exc:
        return [{"line": exc.lineno or 0, "function": "", "problem": f"SyntaxError: {exc.msg}"}]
    except (ValueError, RecursionError) as exc:
        return [{"line": 0, "function": "", "problem": f"could not parse the script: {exc}"}]
    linter = _Linter()
    linter.probed = _probed_names(tree)
    linter.visit(tree)
    return linter.issues


def summary(issues: list[dict[str, Any]]) -> str:
    parts = []
    for item in issues[:5]:
        parts.append(f"line {item.get('line', 0)}: {item['problem']}")
    more = f" (+{len(issues) - 5} more)" if len(issues) > 5 else ""
    return "; ".join(parts) + more


def next_step(issues: list[dict[str, Any]]) -> str:
    sigs = []
    for item in issues:
        sig = item.get("signature")
        if sig and sig not in sigs:
            sigs.append(sig)
    text = "Nothing was sent to Vectorworks. Fix the vs.* calls listed in error.details.issues"
    if sigs:
        text += " - correct signature" + ("s" if len(sigs) > 1 else "") + ": " + "; ".join(sigs[:5])
    text += (". COLOR = (r, g, b) tuple with 0..65535 components, POINT = (x, y). Only if you are certain the call "
             "is valid (e.g. a function newer than the 2025 stub), repeat with lint=false.")
    return text
